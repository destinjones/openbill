function markdownFiles() {
  const out = [];
  for (const e of readdirSync(ROOT, { withFileTypes: true })) {
    if (e.isFile() && e.name.toLowerCase().endsWith('.md')) out.push(join(ROOT, e.name));
  }
  const walk = (dir) => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.isDirectory()) {
        if (!SKIP_DIRS.has(e.name)) walk(join(dir, e.name));
      } else if (e.isFile() && e.name.toLowerCase().endsWith('.md')) out.push(join(dir, e.name));
    }
  };
  walk(join(ROOT, 'docs'));
  walk(join(ROOT, '.github'));
  return out.sort();
}

/** Does `abs` exist with exactly this case in every segment below ROOT? Returns 'file', 'dir' or null. */
function existsExact(abs) {
  const r = relative(ROOT, abs);
  if (r === '') return 'dir';
  if (r.startsWith('..') || resolve(ROOT, r) !== abs) return null;
  let cur = ROOT;
  for (const seg of r.split(sep)) {
    let names;
    try {
      names = readdirSync(cur);
    } catch {
      return null;
    }
    if (!names.includes(seg)) return null;
    cur = join(cur, seg);
  }
  try {
    return statSync(cur).isDirectory() ? 'dir' : 'file';
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------- markdown

/** Blank out fenced code blocks and HTML comments, keeping line numbers. */
function stripFences(md) {
  const noComments = md.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '));
  const lines = noComments.split(/\r?\n/);
  let fence = null;
  return lines
    .map((line) => {
      const m = /^\s*(`{3,}|~{3,})/.exec(line);
      if (fence) {
        if (m && m[1][0] === fence[0] && m[1].length >= fence.length && /^\s*[`~]+\s*$/.test(line)) fence = null;
        return '';
      }
      if (m) {
        fence = m[1];
        return '';
      }
      return line;
    })
    .join('\n');
}

/** Blank out inline code spans (any backtick run length, may span lines). */
function stripInlineCode(text) {
  let out = '';
  let i = 0;
  while (i < text.length) {
    if (text[i] !== '`') {
      out += text[i++];
      continue;
    }
    let j = i;
    while (text[j] === '`') j++;
    const run = j - i;
    let k = j;
    let close = -1;
    while (k < text.length) {
      const n = text.indexOf('`', k);
      if (n < 0) break;
      let e = n;
      while (text[e] === '`') e++;
      if (e - n === run) {
        close = n;
        break;
      }
      k = e;
    }
    if (close < 0) {
      out += text.slice(i, j); // unmatched backticks are literal
      i = j;
      continue;
    }
    out += text.slice(i, close + run).replace(/[^\n]/g, ' ');
    i = close + run;
  }
  return out;
}

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };

function decodeEntities(s) {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e) => {
    if (e[0] === '#') {
      const cp = e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(cp) ? String.fromCodePoint(cp) : m;
    }
    return Object.prototype.hasOwnProperty.call(ENTITIES, e.toLowerCase()) ? ENTITIES[e.toLowerCase()] : m;
  });
}

/** The text GitHub renders for a heading's inline markdown. */
function headingText(raw) {
  const codes = [];
  let s = raw.replace(/(`+)([\s\S]*?[^`])\1(?!`)/g, (m, ticks, body) => {
    codes.push(body.trim() === '' ? body : body.replace(/^ (.*) $/, '$1'));
    return `\u0000${codes.length - 1}\u0000`;
  });
  s = s
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\[[^\]]*\]/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/\\([!-/:-@[-`{-~])/g, '$1')
    .replace(/(^|[^\p{L}\p{N}_])_{1,3}(?=\S)([\s\S]*?\S)_{1,3}(?![\p{L}\p{N}_])/gu, '$1$2')
    .replace(/\*/g, '');
  s = decodeEntities(s);
  return s.replace(/\u0000(\d+)\u0000/g, (m, i) => codes[Number(i)]);
}

/** github-slugger: lower-case, drop punctuation and symbols, spaces to hyphens. */
function githubSlug(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, '')
    .replace(/ /g, '-');
}

/** Heading anchors of a markdown file, with GitHub's -1, -2 suffixes for repeats, plus HTML ids. */
function markdownAnchors(md) {
  const text = stripFences(md);
  const lines = text.split('\n');
  const slugs = new Set();
  const seen = new Map();
  const add = (raw) => {
    const base = githubSlug(headingText(raw));
    let slug = base;
    if (seen.has(base)) {
      let n = seen.get(base);
      do {
        n += 1;
        slug = `${base}-${n}`;
      } while (seen.has(slug));
      seen.set(base, n);
    }
    seen.set(slug, seen.get(slug) || 0);
    slugs.add(slug);
  };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const atx = /^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$/.exec(line);
    if (atx) {
      add(atx[2] || '');
      continue;
    }
    const next = lines[i + 1];
    if (
      next !== undefined &&
      /^ {0,3}(=+|-+)[ \t]*$/.test(next) &&
      line.trim() !== '' &&
      !/^ {0,3}([-*+]\s|\d+[.)]\s|>|\||#)/.test(line) &&
      (i === 0 || lines[i - 1].trim() === '' || /^ {0,3}#/.test(lines[i - 1]))
    ) {
      add(line.trim());
      i += 1;
    }
  }
  for (const id of htmlIds(text)) slugs.add(id);
  return slugs;
}

/** Link destinations in markdown: [text](dest), ![alt](src), [ref]: dest, <autolink>, raw HTML href/src, bare URLs. */
function markdownLinks(md) {
  const text = stripInlineCode(stripFences(md));
  const lineOf = (index) => text.slice(0, index).split('\n').length;
  const out = [];
  const inline = /!?\[((?:[^[\]]|\[(?:[^[\]]|\[[^[\]]*\])*\])*)\]\(\s*(<[^>\n]*>|(?:[^\s()]|\((?:[^\s()])*\))*)(?:\s+(?:"[^"]*"|'[^']*'|\([^)]*\)))?\s*\)/g;
  const scan = (s, offset) => {
    for (const m of s.matchAll(inline)) {
      const dest = m[2].startsWith('<') ? m[2].slice(1, -1) : m[2];
      out.push({ target: dest, line: lineOf(offset + m.index) });
      if (m[1].includes('](')) scan(m[1], offset + m.index + 1 + (m[0][0] === '!' ? 1 : 0));
    }
  };
  scan(text, 0);
  for (const m of text.matchAll(/^ {0,3}\[[^\]\n]+\]:[ \t]*(<[^>\n]*>|\S+)/gm)) {
    out.push({ target: m[1].startsWith('<') ? m[1].slice(1, -1) : m[1], line: lineOf(m.index) });
  }
  for (const m of text.matchAll(/<(https?:\/\/[^>\s]+)>/g)) out.push({ target: m[1], line: lineOf(m.index), external: true });
  for (const l of htmlLinks(text)) out.push({ target: l.target, line: lineOf(l.index) });
  for (const m of text.matchAll(/(?<![\w(<"'=\]/])https?:\/\/[^\s<>()[\]]+(?:\([^\s<>()]*\)[^\s<>()[\]]*)*/g)) {
    out.push({ target: m[0].replace(/[.,:;!?'"*_~]+$/, ''), line: lineOf(m.index), external: true });
  }
  return out;
}

// ---------------------------------------------------------------- HTML

function stripHtmlCode(html) {
  return html
    .replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/<(script|style|template)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, (m) => m.replace(/[^\n]/g, ' '));
}

function attrValues(html, names) {
  const out = [];
  const attr = new RegExp(`\\s(${names})\\s*=\\s*("([^"]*)"|'([^']*)'|([^\\s"'>]+))`, 'g');
  // An element can carry several such attributes; scan each tag.
  for (const tag of html.matchAll(/<[a-zA-Z][^>]*>/g)) {
    for (const m of tag[0].matchAll(attr)) {
      out.push({ name: m[1].toLowerCase(), value: decodeEntities(m[3] ?? m[4] ?? m[5] ?? ''), index: tag.index });
    }
  }
  return out;
}

function htmlIds(html) {
  const ids = new Set();
  for (const a of attrValues(stripHtmlCode(html), 'id|name')) {
    if (a.name === 'id' || a.name === 'name') ids.add(a.value);
  }
  return ids;
}

function htmlLinks(html) {
  return attrValues(stripHtmlCode(html), 'href|src')
    .filter((a) => a.name === 'href' || a.name === 'src')
    .map((a) => ({ target: a.value, index: a.index }));
}

// ---------------------------------------------------------------- resolution

const anchorCache = new Map();

function anchorsOf(abs) {
  if (anchorCache.has(abs)) return anchorCache.get(abs);
  const text = readFileSync(abs, 'utf8');
  const ext = extname(abs).toLowerCase();
  const anchors = ext === '.md' ? markdownAnchors(text) : ext === '.html' || ext === '.htm' ? htmlIds(text) : null;
  anchorCache.set(abs, anchors);
  return anchors;
}

// openbill.html keeps its state in the hash (ARCHITECTURE.md, "The page": #drug=<name>&qty=<n>),
// so a link like openbill.html#drug=ELIQUIS%205%20MG%20TABLET is a card, not an anchor: the
// drug must be a product in data/drugs.json and qty, when given, a positive number.
let productNames = null;

function checkStateHash(rawHash) {
  const params = new URLSearchParams(rawHash);
  const problems = [];
  if (params.has('drug')) {
    if (!productNames) {
      const doc = JSON.parse(readFileSync(join(ROOT, 'data', 'drugs.json'), 'utf8'));
      productNames = new Set(doc.rows.map((r) => r.name));
    }
    const drug = params.get('drug');
    if (!productNames.has(drug)) problems.push(`#drug=${drug} is not a product in data/drugs.json`);
  }
  if (params.has('qty') && !(Number(params.get('qty')) > 0)) problems.push(`qty=${params.get('qty')} is not a positive number`);
  return problems.length ? problems.join('; ') : null;
}

const REPO_BLOB_RE = new RegExp(`^${REPO_URL.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}/(?:blob|tree)/[^/]+/([^?#]*)(?:\\?[^#]*)?(?:#(.*))?$`);

function isOwnGitHub(url) {
  return url === REPO_URL || url.startsWith(`${REPO_URL}/`) || url.startsWith(`${REPO_URL}#`) || url.startsWith(`${REPO_URL}?`) || url.startsWith(`${REPO_URL}.git`);
}

/** Check one link from file `fromAbs`; returns a problem string, or null when it resolves. */
function checkLocal(fromAbs, target) {
  const t = target.trim();
  if (t === '') return 'empty link';
  if (/^(mailto|tel):/i.test(t)) return null;
  if (/^data:/i.test(t)) return null;
  if (/^javascript:/i.test(t)) return 'javascript: link (the CSP forbids it)';
  let pathPart;
  let anchor;
  let base;
  const own = REPO_BLOB_RE.exec(t);
  if (own) {
    pathPart = own[1];
    anchor = own[2];
    base = ROOT;
    if (pathPart === '') return null;
  } else if (/^[a-z][a-z0-9+.-]*:/i.test(t) || t.startsWith('//')) {
    return null; // external: checked separately when OPENBILL_CHECK_EXTERNAL=1
  } else {
    const hash = t.indexOf('#');
    pathPart = (hash < 0 ? t : t.slice(0, hash)).replace(/\?.*$/, '');
    anchor = hash < 0 ? undefined : t.slice(hash + 1);
    base = pathPart.startsWith('/') ? ROOT : dirname(fromAbs);
    if (pathPart.startsWith('/')) pathPart = pathPart.slice(1);
  }
  let decodedPath;
  let decodedAnchor;
  try {
    decodedPath = decodeURIComponent(pathPart);
    decodedAnchor = anchor === undefined ? undefined : decodeURIComponent(anchor);
  } catch {
    return 'badly percent-encoded link';
  }
  let abs = decodedPath === '' ? fromAbs : resolve(base, decodedPath);
  const r = relative(ROOT, abs);
  if (r.startsWith('..') || resolve(ROOT, r) !== abs) return `points outside the repository (${decodedPath})`;
  const kind = existsExact(abs);
  if (!kind) {
    const shown = rel(abs);
    return HTML_PAGES.includes(shown)
      ? `${shown} does not exist yet; it is generated by node build.js`
      : shown === 'docs/DATA-QUALITY.md'
      ? 'docs/DATA-QUALITY.md does not exist yet; it is generated by node build.js'
      : `${shown} does not exist (names are case-sensitive)`;
  }
  if (decodedAnchor === undefined || decodedAnchor === '') return null;
  if (rel(abs) === 'openbill.html' && anchor.includes('=')) return checkStateHash(anchor);
  if (kind === 'dir') {
    const readme = ['README.md', 'readme.md'].map((n) => join(abs, n)).find((p) => existsExact(p) === 'file');
    if (!readme) return `#${decodedAnchor} on a folder with no README.md`;
    abs = readme;
  }
  const anchors = anchorsOf(abs);
  if (anchors === null) {
    return /^L\d+(-L\d+)?$/.test(decodedAnchor) ? null : `#${decodedAnchor} into ${rel(abs)}, which has no anchors (only #L<line> works there)`;
  }
  if (!anchors.has(decodedAnchor)) return `#${decodedAnchor} is not a heading or id in ${rel(abs)}`;
  return null;
}

function linksOf(abs) {
  const text = readFileSync(abs, 'utf8');
  if (abs.toLowerCase().endsWith('.md')) return markdownLinks(text);
  const stripped = stripHtmlCode(text);
  const lineOf = (i) => stripped.slice(0, i).split('\n').length;
  return htmlLinks(text).map((l) => ({ target: l.target, line: lineOf(l.index) }));
}

function problemsIn(abs) {
  const problems = [];
  for (const l of linksOf(abs)) {
    const p = checkLocal(abs, l.target);
    if (p) problems.push(`${rel(abs)}:${l.line}: ${JSON.stringify(l.target)}: ${p}`);
  }
  return problems;
}

