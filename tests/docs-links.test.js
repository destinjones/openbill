// Which browsers the Playwright checks run in is a claim the docs make (decision 33): README and
// CONTRIBUTING must name what playwright.config.js runs, CI must install it, and no sentence may
// say the checks run in an engine the config does not use.
test('README and CONTRIBUTING name the browsers the Playwright config runs, and CI installs them', () => {
  const ENGINES = { chromium: 'Chromium', firefox: 'Firefox', webkit: 'WebKit' };
  const config = readFileSync(join(ROOT, 'playwright.config.js'), 'utf8');
  const named = [...config.matchAll(/browserName:\s*['"](\w+)['"]/g)].map((m) => m[1]);
  const engines = [...new Set(named.length ? named : ['chromium'])].sort();
  const problems = [];
  for (const e of engines) if (!ENGINES[e]) problems.push(`playwright.config.js uses an unknown browserName ${e}`);
  const ci = readFileSync(join(ROOT, '.github', 'workflows', 'ci.yml'), 'utf8');
  const install = ci.match(/playwright install([^\n]*)/);
  if (!install) problems.push('ci.yml does not install a Playwright browser');
  else for (const e of engines) if (!new RegExp(`\\b${e}\\b`).test(install[1])) problems.push(`ci.yml does not install ${e}`);
  const unused = Object.keys(ENGINES).filter((e) => !engines.includes(e));
  for (const file of ['README.md', 'CONTRIBUTING.md']) {
    const text = readFileSync(join(ROOT, file), 'utf8').replace(/\s+/g, ' ');
    if (engines.length === 1) {
      if (!new RegExp(`${ENGINES[engines[0]]} only`).test(text)) problems.push(`${file} does not say the browser checks run in ${ENGINES[engines[0]]} only`);
    } else {
      for (const e of engines) if (!new RegExp(ENGINES[e], 'i').test(text)) problems.push(`${file} does not name ${ENGINES[e]}`);
    }
    for (const sentence of text.split(/(?<=[.!?])\s+/)) {
      for (const e of unused) {
        if (!new RegExp(`\\b${ENGINES[e]}\\b`, 'i').test(sentence)) continue;
        if (!/playwright|browser checks?|tested|tests? run/i.test(sentence)) continue;
        if (!/\bnot\b|n't|\bonly\b/i.test(sentence)) problems.push(`${file} may say the checks run in ${ENGINES[e]}: "${sentence.slice(0, 160)}"`);
      }
    }
  }
  assert.deepEqual(problems, []);
});

